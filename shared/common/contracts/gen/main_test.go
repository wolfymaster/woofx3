// The smallest contract has no integer field and a single outcome status, so
// it exercises the parts of each template that are emitted only when used.
func TestEmitsTheSmallestContract(t *testing.T) {
	contract, err := parsePlatformGateway([]byte(validContract))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	goSource, err := emitGo(contract)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	if strings.Contains(string(goSource), `"math"`) || strings.Contains(string(goSource), "func checkInteger") {
		t.Fatalf("Go output imports math or declares checkInteger without an integer field")
	}
	tsSource, err := emitTS(contract)
	if err != nil {
		t.Fatalf("emitTS: %v", err)
	}
	if strings.Contains(string(tsSource), "function readOptionalInteger") {
		t.Fatalf("TypeScript output declares an integer reader without an integer field")
	}
}


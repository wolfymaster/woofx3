package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	contractPath = "../platform-gateway.json"
	// The committed outputs, relative to this package. They double as the
	// golden files, so CI fails on an edit to the contract, a template or an
	// emitter that was not regenerated.
	goOutputPath = "../../golang/platformgateway/catalog_gen.go"
	tsOutputPath = "../../../clients/typescript/api/platform-gateway.gen.ts"
)

func readContract(t *testing.T) platformGateway {
	t.Helper()
	raw, err := os.ReadFile(contractPath)
	if err != nil {
		t.Fatalf("reading contract: %v", err)
	}
	contract, err := parsePlatformGateway(raw)
	if err != nil {
		t.Fatalf("parsing contract: %v", err)
	}
	return contract
}

func TestGoldenOutputs(t *testing.T) {
	contract := readContract(t)
	emitters := []struct {
		name string
		path string
		emit func(platformGateway) ([]byte, error)
	}{
		{"go", goOutputPath, emitGo},
		{"ts", tsOutputPath, emitTS},
	}
	for _, e := range emitters {
		t.Run(e.name, func(t *testing.T) {
			want, err := os.ReadFile(e.path)
			if err != nil {
				t.Fatalf("reading committed output: %v", err)
			}
			got, err := e.emit(contract)
			if err != nil {
				t.Fatalf("emitting: %v", err)
			}
			if !bytes.Equal(got, want) {
				t.Fatalf("%s is stale; run scripts/gen-contracts.sh", e.path)
			}
		})
	}
}

func TestRunWritesBothOutputs(t *testing.T) {
	dir := t.TempDir()
	goPath, tsPath := filepath.Join(dir, "out.go"), filepath.Join(dir, "out.ts")
	if err := dispatch([]string{"platform-gateway", contractPath, goPath, tsPath}); err != nil {
		t.Fatalf("dispatch: %v", err)
	}
	for _, path := range []string{goPath, tsPath} {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		header := "// Code generated by shared/common/contracts/gen from shared/common/contracts/platform-gateway.json; DO NOT EDIT.\n"
		if !strings.HasPrefix(string(raw), header) {
			t.Fatalf("%s does not start with the generated-code header", path)
		}
	}
}

func TestDispatchRefusesBadArguments(t *testing.T) {
	cases := map[string][]string{
		"no contract":       nil,
		"unknown contract":  {"companion", contractPath},
		"missing arguments": {"platform-gateway", contractPath},
	}
	for name, args := range cases {
		t.Run(name, func(t *testing.T) {
			if err := dispatch(args); err == nil {
				t.Fatal("want an error")
			}
		})
	}
}

// validContract is the smallest contract the generator accepts; each case
// below breaks one rule of it.
const validContract = `{
  "subjects": {"send": "platform.gateway.send", "capabilities": "platform.gateway.capabilities", "fieldOptions": "platform.gateway.field_options"},
  "platforms": [{"id": "twitch", "displayName": "Twitch"}],
  "requesters": ["workflow"],
  "failureCodes": ["invalid"],
  "outcomeStatuses": ["delivered"],
  "unavailableReasons": ["stopped"],
  "actions": [{"id": "chat.send", "fields": [{"name": "message", "type": "string", "required": true, "maxLength": 500}]}]
}`

// The smallest contract has no integer field and a single outcome status, so
// it exercises the parts of each template that are emitted only when used.
func TestEmitsTheSmallestContract(t *testing.T) {
	contract, err := parsePlatformGateway([]byte(validContract))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	goSource, err := emitGo(contract)
	if err != nil {
		t.Fatalf("emitGo: %v", err)
	}
	if strings.Contains(string(goSource), `"math"`) || strings.Contains(string(goSource), "func checkInteger") {
		t.Fatalf("Go output imports math or declares checkInteger without an integer field")
	}
	tsSource, err := emitTS(contract)
	if err != nil {
		t.Fatalf("emitTS: %v", err)
	}
	if strings.Contains(string(tsSource), "function readOptionalInteger") {
		t.Fatalf("TypeScript output declares an integer reader without an integer field")
	}
}

func TestParseRefusesBadContracts(t *testing.T) {
	cases := []struct {
		name    string
		from    string
		to      string
		wantErr string
	}{
		{"unknown top-level key", `"requesters"`, `"requestors": ["x"], "requesters"`, "unknown field"},
		{"unknown field key", `"required": true`, `"required": true, "pattern": "x"`, "unknown field"},
		{"duplicate platform", `[{"id": "twitch", "displayName": "Twitch"}]`, `[{"id": "twitch", "displayName": "Twitch"}, {"id": "twitch", "displayName": "Twitch again"}]`, "duplicate platform"},
		{"duplicate requester", `["workflow"]`, `["workflow", "workflow"]`, "duplicate value"},
		{"duplicate action", `"actions": [`, `"actions": [{"id": "chat.send", "fields": [{"name": "message", "type": "string", "required": true, "maxLength": 1}]}, `, "duplicate action"},
		{"duplicate field", `"maxLength": 500}]`, `"maxLength": 500}, {"name": "message", "type": "string", "required": false, "maxLength": 5}]`, "duplicate field"},
		{"shared subject", `"platform.gateway.capabilities"`, `"platform.gateway.send"`, "is also"},
		{"bad subject", `"platform.gateway.field_options"`, `"Field Options"`, "not a dotted lowercase subject"},
		{"no platforms", `[{"id": "twitch", "displayName": "Twitch"}]`, `[]`, "platforms: is required"},
		{"missing display name", `"displayName": "Twitch"`, `"displayName": " "`, "displayName"},
		{"unknown outcome status", `["delivered"]`, `["delivered", "exploded"]`, "no outcome shape"},
		{"unbounded string", `, "maxLength": 500`, ``, "positive maxLength"},
		{"unknown field type", `"type": "string"`, `"type": "boolean"`, "not one of string, integer"},
		{"integer without bounds", `"type": "string", "required": true, "maxLength": 500`, `"type": "integer", "required": true, "min": 1`, "needs min and max"},
		{"inverted bounds", `"type": "string", "required": true, "maxLength": 500`, `"type": "integer", "required": true, "min": 9, "max": 1`, "above max"},
		{"fields and oneOf", `"fields": [`, `"oneOf": [{"name": "a", "fields": [{"name": "x", "type": "string", "required": true, "maxLength": 1}]}], "fields": [`, "exactly one of fields or oneOf"},
		{"one variant", `"fields": [{"name": "message", "type": "string", "required": true, "maxLength": 500}]`, `"oneOf": [{"name": "only", "fields": [{"name": "message", "type": "string", "required": true, "maxLength": 500}]}]`, "at least two variants"},
		{"overlapping variants", `"fields": [{"name": "message", "type": "string", "required": true, "maxLength": 500}]`, `"oneOf": [{"name": "a", "fields": [{"name": "message", "type": "string", "required": true, "maxLength": 5}]}, {"name": "b", "fields": [{"name": "message", "type": "string", "required": true, "maxLength": 5}]}]`, "disjoint fields"},
		{"trailing data", `}]}]
}`, `}]}]
} {}`, "trailing data"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if !strings.Contains(validContract, tc.from) {
				t.Fatalf("the case's anchor %q is not in the valid contract", tc.from)
			}
			broken := strings.Replace(validContract, tc.from, tc.to, 1)
			_, err := parsePlatformGateway([]byte(broken))
			if err == nil {
				t.Fatal("want an error")
			}
			if !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("error %q does not mention %q", err, tc.wantErr)
			}
		})
	}
}

func TestNames(t *testing.T) {
	cases := []struct {
		in, goName, pascal, screaming string
	}{
		{"chat.send", "ChatSend", "ChatSend", "CHAT_SEND"},
		{"rate_limited", "RateLimited", "RateLimited", "RATE_LIMITED"},
		{"replyToMessageId", "ReplyToMessageID", "ReplyToMessageId", "REPLY_TO_MESSAGE_ID"},
		{"api", "API", "Api", "API"},
	}
	for _, tc := range cases {
		t.Run(tc.in, func(t *testing.T) {
			if got := goName(tc.in); got != tc.goName {
				t.Errorf("goName = %q, want %q", got, tc.goName)
			}
			if got := pascalName(tc.in); got != tc.pascal {
				t.Errorf("pascalName = %q, want %q", got, tc.pascal)
			}
			if got := screamingName(tc.in); got != tc.screaming {
				t.Errorf("screamingName = %q, want %q", got, tc.screaming)
			}
		})
	}
}

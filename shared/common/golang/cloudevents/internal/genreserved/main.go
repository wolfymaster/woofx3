// Command genreserved writes reserved_data.go from the reserved-subjects
// contract shared by the Go, TypeScript and Rust services. go:embed cannot
// reach a file outside the module, so the lists are compiled in instead;
// TestReservedDataMatchesContract fails when the two drift.
//
// Usage (from the cloudevents package directory, via go generate):
//
//	genreserved <contract.json> <output.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strconv"
)

// contract mirrors reservedSubjectsContract in reserved.go; unknown keys are
// refused so a list added to the JSON cannot be silently left out.
type contract struct {
	CommandSubjectPrefixes []string `json:"commandSubjectPrefixes"`
	EngineAssertedPrefixes []string `json:"engineAssertedPrefixes"`
	PlatformEventEntries   []string `json:"platformEventEntries"`
	UploadReservedPrefixes []string `json:"uploadReservedPrefixes"`
	EngineModuleSegments   []string `json:"engineModuleSegments"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genreserved <contract.json> <output.go>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "genreserved:", err)
		os.Exit(1)
	}
}

func run(contractPath, outputPath string) error {
	raw, err := os.ReadFile(contractPath)
	if err != nil {
		return fmt.Errorf("reading contract: %w", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var c contract
	if err := decoder.Decode(&c); err != nil {
		return fmt.Errorf("decoding %s: %w", contractPath, err)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by internal/genreserved from shared/common/contracts/reserved-subjects.json; DO NOT EDIT.\n\n")
	out.WriteString("package cloudevents\n\n")
	out.WriteString("var reservedSubjects = reservedSubjectsContract{\n")
	writeList(&out, "CommandSubjectPrefixes", c.CommandSubjectPrefixes)
	writeList(&out, "EngineAssertedPrefixes", c.EngineAssertedPrefixes)
	writeList(&out, "PlatformEventEntries", c.PlatformEventEntries)
	writeList(&out, "UploadReservedPrefixes", c.UploadReservedPrefixes)
	writeList(&out, "EngineModuleSegments", c.EngineModuleSegments)
	out.WriteString("}\n")

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("formatting generated source: %w", err)
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outputPath, err)
	}
	return nil
}

func writeList(out *bytes.Buffer, field string, entries []string) {
	fmt.Fprintf(out, "%s: []string{\n", field)
	for _, entry := range entries {
		fmt.Fprintf(out, "%s,\n", strconv.Quote(entry))
	}
	out.WriteString("},\n")
}

//! Writes Rust types for a bundled JSON Schema document: `contracts-spike-gen <bundle.json> <out.rs>`.

use std::{env, fs, process::ExitCode};

use typify::{TypeSpace, TypeSpaceSettings};

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("contracts-spike-gen: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let args: Vec<String> = env::args().collect();
    let [_, input, output] = args.as_slice() else {
        return Err("usage: contracts-spike-gen <bundle.json> <out.rs>".to_string());
    };
    let text = fs::read_to_string(input).map_err(|e| format!("reading {input}: {e}"))?;
    let schema: schemars::schema::RootSchema = serde_json::from_str(&text).map_err(|e| format!("parsing {input}: {e}"))?;
    let mut space = TypeSpace::new(&TypeSpaceSettings::default());
    space.add_root_schema(schema).map_err(|e| format!("typify: {e}"))?;
    let file = syn::parse2::<syn::File>(space.to_stream().map_err(|e| format!("typify: {e}"))?).map_err(|e| format!("rendering: {e}"))?;
    let body = prettyplease::unparse(&file);
    let header = "// Generated by contracts-spike-gen (typify) from spike/contracts/schemas. Do not edit.\n#![allow(clippy::redundant_closure_call, clippy::needless_lifetimes, clippy::match_single_binding, clippy::clone_on_copy)]\n\n";
    fs::write(output, format!("{header}{body}")).map_err(|e| format!("writing {output}: {e}"))
}

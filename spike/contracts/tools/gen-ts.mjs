// Generates TypeScript types for every schema file with json-schema-to-typescript.
import { compile } from "json-schema-to-typescript";
import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const out = process.argv[2];
const files = ["common", "platform-gateway", "events"].flatMap((d) =>
  readdirSync(join(root, "schemas", d)).map((f) => `${d}/${f}`)
);
const index = {
  title: "AnyContract",
  description: "Every message schema; exists so each one is emitted.",
  anyOf: files.map((f) => ({ $ref: `${root}/schemas/${f}` })),
};
const ts = await compile(index, "AnyContract", {
  cwd: root + "/schemas/",
  bannerComment: "/* Generated by json-schema-to-typescript from spike/contracts/schemas. Do not edit. */",
  additionalProperties: false,
  maxItems: -1,
  format: false,
  declareExternallyReferenced: true,
});
writeFileSync(out, ts);
